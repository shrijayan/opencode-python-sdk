_ISOLATION_ENV = {
    # Ignore the working directory's opencode.json, AGENTS.md and .opencode folder.
    "OPENCODE_CONFIG_PROJECT_DISABLE": "1",
    # Ignore Claude Code skills and instructions found in the project or home directory.
    "OPENCODE_DISABLE_CLAUDE_CODE": "1",
}


class ServerStartError(OpencodeError):
    """``opencode serve`` could not be started or did not report its address in time."""

    def __init__(self, message: str, *, output: str = "") -> None:
        super().__init__(f"{message}\n\nServer output:\n{output}" if output else message)
        self.output = output


class OpencodeServer:
    """Runs ``opencode serve`` as a child process for the lifetime of a ``with`` block.

    The server listens on a free local port and requires a random password, which is passed to clients created
    with :meth:`client`. It runs in ``--stdio`` mode, so it also exits if this process dies.

    Args:
        cwd: Directory the server runs in, which is its default project location.
        config: OpenCode configuration as a mapping, passed through ``OPENCODE_CONFIG_CONTENT``.
        isolated: Ignore project and Claude Code configuration found on disk, for reproducible embedded use.
        env: Extra environment variables for the server.
        hostname: Interface to bind. Keep ``127.0.0.1`` unless the server must be reachable from other hosts.
        port: Port to bind. ``0`` picks a free port.
        password: Server password. A random one is generated by default.
        binary: The ``opencode`` executable, looked up on ``PATH`` by default.
        startup_timeout: Seconds to wait for the server to report its address.

    Example::

        with OpencodeServer(cwd="/path/to/repo", isolated=True) as server:
            client = server.client()
            print(client.server.info().version)
    """

    def __init__(
        self,
        *,
        cwd: str | os.PathLike[str] | None = None,
        config: Mapping[str, Any] | None = None,
        isolated: bool = False,
        env: Mapping[str, str] | None = None,
        hostname: str = "127.0.0.1",
        port: int = 0,
        password: str | None = None,
        binary: str | os.PathLike[str] = "opencode",
        startup_timeout: float = 60.0,
    ) -> None:
        self.cwd = Path(cwd) if cwd is not None else None
        self.config = dict(config) if config is not None else None
        self.isolated = isolated
        self.env = dict(env or {})
        self.hostname = hostname
        self.port = port
        self.password = password if password is not None else secrets.token_urlsafe(32)
        self.binary = os.fspath(binary)
        self.startup_timeout = startup_timeout
        self._process: subprocess.Popen[str] | None = None
        self._url: str | None = None
        self._output: collections.deque[str] = collections.deque(maxlen=200)
        self._lock = threading.Lock()
        self._threads: list[threading.Thread] = []

    @property
    def url(self) -> str:
        """The server's base URL. Available once started."""
        if self._url is None:
            raise OpencodeError("The OpenCode server is not running. Call start() or use it as a context manager.")
        return self._url

    @property
    def process(self) -> subprocess.Popen[str] | None:
        return self._process

    @property
    def running(self) -> bool:
        return self._process is not None and self._process.poll() is None

    def client(self, *, directory: str | os.PathLike[str] | None = None, timeout: Timeout | None = None) -> Opencode:
        """Returns a sync client connected to this server."""
        kwargs: dict[str, Any] = {} if timeout is None else {"timeout": timeout}
        return Opencode(self.url, password=self.password, username=DEFAULT_USERNAME, directory=directory, **kwargs)

    def async_client(
        self, *, directory: str | os.PathLike[str] | None = None, timeout: Timeout | None = None
    ) -> AsyncOpencode:
        """Returns an async client connected to this server."""
        kwargs: dict[str, Any] = {} if timeout is None else {"timeout": timeout}
        return AsyncOpencode(self.url, password=self.password, username=DEFAULT_USERNAME, directory=directory, **kwargs)

    def _command(self) -> list[str]:
        executable = shutil.which(self.binary)
        if executable is None:
            raise ServerStartError(
                f"Could not find the {self.binary!r} executable. Install OpenCode (https://opencode.ai) "
                "or pass binary= with its path."
            )
        return [executable, "serve", "--stdio", "--hostname", self.hostname, "--port", str(self.port)]

    def _environment(self) -> dict[str, str]:
        environment = dict(os.environ)
        # The server reads its password from the environment and removes it from what its tools inherit.
        environment.pop("OPENCODE_SERVER_PASSWORD", None)
        environment["OPENCODE_PASSWORD"] = self.password
        if self.isolated:
            environment.update(_ISOLATION_ENV)
        if self.config is not None:
            environment["OPENCODE_CONFIG_CONTENT"] = json.dumps(self.config)
        environment.update(self.env)
        return environment

    def start(self) -> Self:
        """Starts the server and waits until it reports its address."""
        with self._lock:
            if self.running:
                return self
            self._output.clear()
            command = self._command()
            try:
                process = subprocess.Popen(
                    command,
                    cwd=self.cwd,
                    env=self._environment(),
                    stdin=subprocess.PIPE,
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    text=True,
                    encoding="utf-8",
                    errors="replace",
                    bufsize=1,
                    # Keep Ctrl+C in a terminal from reaching the server before we can shut it down cleanly.
                    start_new_session=sys.platform != "win32",
                )
            except OSError as exc:
                raise ServerStartError(f"Could not start {command[0]}: {exc}") from exc
            self._process = process
            lines: queue.Queue[str | None] = queue.Queue()
            assert process.stdout is not None
            assert process.stderr is not None
            self._pump(process.stdout, lines)
            self._pump(process.stderr, None)

            url = self._wait_for_url(process, lines)
            if url is None:
                output = "\n".join(self._output)
                self._shutdown(process)
                self._process = None
                raise ServerStartError("OpenCode server did not start", output=output)
            self._url = url
            return self

    def _pump(self, stream: IO[str], lines: queue.Queue[str | None] | None) -> None:
        def run() -> None:
            try:
                for line in stream:
                    stripped = line.rstrip("\n")
                    self._output.append(stripped)
                    if lines is not None:
                        lines.put(stripped)
            except (OSError, ValueError):
                pass
            finally:
                if lines is not None:
                    lines.put(None)

        thread = threading.Thread(target=run, name="opencode-server-output", daemon=True)
        thread.start()
        self._threads.append(thread)

    def _wait_for_url(self, process: subprocess.Popen[str], lines: queue.Queue[str | None]) -> str | None:
        deadline = time.monotonic() + self.startup_timeout
        while (remaining := deadline - time.monotonic()) > 0:
            try:
                line = lines.get(timeout=min(remaining, 0.5))
            except queue.Empty:
                if process.poll() is not None:
                    return None
                continue
            if line is None:
                return None
            try:
                message = json.loads(line)
            except ValueError:
                continue
            url: object = cast("dict[str, Any]", message).get("url") if isinstance(message, dict) else None
            if isinstance(url, str):
                return str(httpx.URL(url))
        return None

    def stop(self, timeout: float = 10.0) -> None:
        """Stops the server: closes its stdin, then terminates it if it has not exited within ``timeout``."""
        with self._lock:
            process = self._process
            self._process = None
            self._url = None
            if process is not None:
                self._shutdown(process, timeout)

    def _shutdown(self, process: subprocess.Popen[str], timeout: float = 10.0) -> None:
        self._terminate(process, timeout)
        # The output threads finish at end of file; then the pipes can be closed.
        for thread in self._threads:
            thread.join(timeout=2)
        self._threads.clear()
        for stream in (process.stdout, process.stderr):
            if stream is not None:
                with contextlib.suppress(OSError):
                    stream.close()

    @staticmethod
    def _terminate(process: subprocess.Popen[str], timeout: float = 10.0) -> None:
        if process.stdin is not None:
            with contextlib.suppress(OSError):
                process.stdin.close()
        try:
            process.wait(timeout=timeout)
            return
        except subprocess.TimeoutExpired:
            process.terminate()
        try:
            process.wait(timeout=5)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait()

    @property
    def output(self) -> str:
        """The last lines the server wrote, for diagnostics."""
        return "\n".join(self._output)

    def __enter__(self) -> Self:
        return self.start()

    def __exit__(
        self, exc_type: type[BaseException] | None, exc: BaseException | None, tb: TracebackType | None
    ) -> None:
        self.stop()


class AsyncOpencodeServer:
    """Async wrapper around :class:`OpencodeServer`; takes the same arguments.

    Example::

        async with AsyncOpencodeServer(isolated=True) as server:
            async with server.client() as client:
                info = await client.server.info()
    """

    def __init__(self, **kwargs: Any) -> None:
        self._server = OpencodeServer(**kwargs)

    @property
    def url(self) -> str:
        return self._server.url

    @property
    def password(self) -> str:
        return self._server.password

    @property
    def running(self) -> bool:
        return self._server.running

    @property
    def output(self) -> str:
        return self._server.output

    def client(
        self, *, directory: str | os.PathLike[str] | None = None, timeout: Timeout | None = None
    ) -> AsyncOpencode:
        """Returns an async client connected to this server."""
        return self._server.async_client(directory=directory, timeout=timeout)

    async def start(self) -> Self:
        await anyio.to_thread.run_sync(self._server.start)
        return self

    async def stop(self, timeout: float = 10.0) -> None:
        await anyio.to_thread.run_sync(lambda: self._server.stop(timeout))

    async def __aenter__(self) -> Self:
        return await self.start()

    async def __aexit__(
        self, exc_type: type[BaseException] | None, exc: BaseException | None, tb: TracebackType | None
    ) -> None:
        await self.stop()
