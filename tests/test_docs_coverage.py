"""Fails when the public API and the documentation drift apart.

Checks, in both directions:

- every resource class and method reachable from the client is rendered in the API reference;
- every name in ``opencode.__all__`` and ``opencode.types`` is rendered or mentioned in ``docs/``;
- every resource group on the client is listed in ``docs/guides/index.md``;
- guides only reference methods and types that exist.

The API reference pages for resources and types are generated by ``docs/hooks/types_reference.py`` at build time,
so these tests load that hook and check its output, plus the hand-written pages.
"""

from __future__ import annotations

import builtins
import importlib.util
import inspect
import re
from pathlib import Path
from types import ModuleType
from typing import Any

import pytest

import opencode
from opencode import resources as opencode_resources, types as opencode_types
from opencode._resource import AsyncAPIResource, SyncAPIResource

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
HOOK = DOCS / "hooks/types_reference.py"
GUIDE_INDEX = DOCS / "guides/index.md"

DIRECTIVE = re.compile(r"^::: (\S+)((?:\n {4}.*)*)", re.M)
MEMBERS_OPTION = re.compile(r"members:\s*\[([^\]]*)\]")


def _load_hook() -> ModuleType:
    spec = importlib.util.spec_from_file_location("docs_hook", HOOK)
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


HOOK_MODULE = _load_hook()


def _hand_written_pages() -> dict[str, str]:
    return {str(path.relative_to(DOCS)): path.read_text() for path in sorted(DOCS.rglob("*.md"))}


def _generated_pages() -> dict[str, str]:
    pages = {"reference/resources.md (generated)": HOOK_MODULE.resources_page()}
    for title, names in HOOK_MODULE.type_groups().items():
        pages[f"reference/types/{title} (generated)"] = HOOK_MODULE.type_page(title, names)
    return pages


HAND_WRITTEN = _hand_written_pages()
ALL_PAGES = {**HAND_WRITTEN, **_generated_pages()}


def _directives() -> dict[str, list[str] | None]:
    """Maps each ``:::`` target to its ``members`` option, or ``None`` when all members are rendered."""
    found: dict[str, list[str] | None] = {}
    for text in ALL_PAGES.values():
        for match in DIRECTIVE.finditer(text):
            members = MEMBERS_OPTION.search(match.group(2))
            found[match.group(1)] = (
                [m.strip().strip("'\"") for m in members.group(1).split(",") if m.strip()] if members else None
            )
    return found


DIRECTIVES = _directives()


def _client() -> opencode.Opencode:
    return opencode.Opencode("http://127.0.0.1:1", password="")


def _resources(obj: object, path: str) -> list[tuple[str, SyncAPIResource]]:
    found: list[tuple[str, SyncAPIResource]] = []
    for name in dir(type(obj)):
        if name.startswith("_"):
            continue
        value = getattr(obj, name)
        if isinstance(value, SyncAPIResource):
            found.append((f"{path}.{name}", value))
            found += _resources(value, f"{path}.{name}")
    return found


RESOURCES = _resources(_client(), "client")


def _public_methods(cls: type) -> list[str]:
    return [
        name
        for name, value in vars(cls).items()
        if not name.startswith(("_", "model_")) and (inspect.isfunction(value) or isinstance(value, property))
    ]


def _source(obj: object) -> str:
    path = inspect.getsourcefile(obj)  # type: ignore[arg-type]
    return str(Path(path).relative_to(ROOT)) if path else "its module"


def _target(cls: type) -> str:
    return f"{cls.__module__}.{cls.__qualname__}"


@pytest.mark.parametrize(("path", "resource"), RESOURCES, ids=[path for path, _ in RESOURCES])
def test_resource_is_rendered(path: str, resource: SyncAPIResource) -> None:
    cls = type(resource)
    assert _target(cls) in DIRECTIVES, (
        f"`{path}` ({_target(cls)}) is not in the API reference. Resource pages are generated by "
        f"docs/hooks/types_reference.py from src/opencode/resources/; check that hook still finds {cls.__name__}."
    )
    for name in _public_methods(cls):
        method = getattr(cls, name)
        assert inspect.getdoc(method), (
            f"`{path}.{name}()` has no docstring, so its reference entry is empty. Add one in codegen/render.py "
            "(generated resources) and run `uv run python -m codegen`."
        )


@pytest.mark.parametrize(("path", "resource"), RESOURCES, ids=[path for path, _ in RESOURCES])
def test_async_resource_matches_sync(path: str, resource: SyncAPIResource) -> None:
    """The docs only render sync resources and say the async twin has the same methods; keep that true."""
    sync_cls = type(resource)
    module = inspect.getmodule(sync_cls)
    async_cls = getattr(module, f"Async{sync_cls.__name__}", None)
    assert async_cls is not None, f"`{path}` has no async twin Async{sync_cls.__name__}"
    assert issubclass(async_cls, AsyncAPIResource)
    assert set(_public_methods(sync_cls)) == set(_public_methods(async_cls)), (
        f"`{path}`: {sync_cls.__name__} and {async_cls.__name__} expose different methods, but the docs say they match."
    )


def _mentioned(name: str) -> bool:
    pattern = re.compile(rf"`{re.escape(name)}(?:\(\))?`|\bopencode\.{re.escape(name)}\b")
    return any(pattern.search(text) for text in HAND_WRITTEN.values())


@pytest.mark.parametrize("name", opencode.__all__)
def test_top_level_export_is_documented(name: str) -> None:
    obj = getattr(opencode, name)
    target = f"opencode.{name}"
    if inspect.isclass(obj) or inspect.isfunction(obj):
        assert target in DIRECTIVES, (
            f"`{target}` is exported but not rendered in the docs. Add `::: {target}` to the matching page under "
            "docs/reference/ (clients.md, server.md, pagination.md or exceptions.md)."
        )
        members = DIRECTIVES[target]
        if members is not None and inspect.isclass(obj):
            missing = [m for m in _public_methods(obj) if m not in members]
            assert not missing, (
                f"`{target}` is rendered with a `members:` list that leaves out {missing}. Add them to the "
                f"`::: {target}` directive in docs/reference/."
            )
    else:
        assert target in DIRECTIVES or _mentioned(name), (
            f"`{target}` is exported but never mentioned in docs/. Render it with `::: {target}` or mention "
            f"`{name}` in a guide."
        )


@pytest.mark.parametrize("name", [n for n in opencode.__all__ if inspect.isclass(getattr(opencode, n))])
def test_top_level_class_has_docstrings(name: str) -> None:
    """Ruff's D1 rules skip private modules, so the hand-written runtime (``_client.py``, ``_server.py``, ...) is
    checked here: every exported class and each of its own public methods and properties needs a docstring."""
    cls = getattr(opencode, name)
    assert cls.__doc__, f"`opencode.{name}` has no docstring. Add one in {_source(cls)}."
    missing = [m for m in _public_methods(cls) if not inspect.getdoc(vars(cls)[m])]
    assert not missing, f"`opencode.{name}` members without a docstring: {missing}. Add them in {_source(cls)}."


def test_every_type_is_rendered() -> None:
    rendered = {name for names in HOOK_MODULE.type_groups().values() for name in names}
    exported = {name for name in dir(opencode_types) if not name.startswith("_") and name[0].isupper()}
    missing = sorted(exported - rendered)
    assert not missing, (
        f"These types are exported from opencode.types but not in the type reference: {missing}. The pages are "
        "generated by docs/hooks/types_reference.py from src/opencode/types/_generated.py; update the hook if "
        "types now live elsewhere."
    )


def test_guide_index_lists_every_resource_group() -> None:
    text = GUIDE_INDEX.read_text()
    top_level = [path for path, _ in RESOURCES if path.count(".") == 1]
    missing = [path for path in top_level if f"`{path}`" not in text]
    assert not missing, (
        f"Resource groups missing from docs/guides/index.md: {missing}. Add a row for each, linking its "
        "reference entry (and a guide, if it needs one)."
    )
    listed = re.findall(r"^\| `(client\.\w+)`", text, re.M)
    stale = [path for path in listed if path not in top_level]
    assert not stale, f"docs/guides/index.md lists groups the client no longer has: {stale}. Remove those rows."


# ---------- Stale references in hand-written pages ----------

CALL = re.compile(r"\bclient((?:\.\w+)+)\(")
FROM_IMPORT = re.compile(r"from opencode(\.types)? import ([\w ,]+)")
QUALIFIED = re.compile(r"\bopencode\.([A-Z]\w+)")
# Only CamelCase words with two or more humps, so `GET`, `DEBUG` or `Authorization` are not taken for types.
BACKTICK_TYPE = re.compile(r"`([A-Z][a-z0-9]+(?:[A-Z][a-z0-9]*)+)`")

# CamelCase names in prose that are not part of this package.
EXTERNAL_NAMES = {"ClientApi", "HttpApi", "OpenCode", "TypeScript"}


def _exists(name: str) -> bool:
    return (
        hasattr(opencode, name)
        or hasattr(opencode_types, name)
        or hasattr(opencode_resources, name)
        or hasattr(builtins, name)
    )


def _stale_references() -> list[str]:
    client = _client()
    problems: list[str] = []
    for page, text in HAND_WRITTEN.items():
        for match in CALL.finditer(text):
            obj: Any = client
            for attr in match.group(1).strip(".").split("."):
                if not hasattr(obj, attr):
                    problems.append(f"{page}: `client{match.group(1)}()` does not exist (no `{attr}`)")
                    break
                obj = getattr(obj, attr)
        for match in FROM_IMPORT.finditer(text):
            module: ModuleType = opencode_types if match.group(1) else opencode
            for name in (n.strip() for n in match.group(2).split(",")):
                if name and not hasattr(module, name):
                    problems.append(f"{page}: `{name}` is imported from {module.__name__} but does not exist")
        for match in QUALIFIED.finditer(text):
            if not hasattr(opencode, match.group(1)):
                problems.append(f"{page}: `opencode.{match.group(1)}` does not exist")
        for match in BACKTICK_TYPE.finditer(text):
            name = match.group(1)
            if name not in EXTERNAL_NAMES and not _exists(name):
                problems.append(f"{page}: `{name}` is not a name in opencode or opencode.types")
    return problems


def test_guides_reference_only_existing_api() -> None:
    problems = _stale_references()
    assert not problems, "Docs reference API that does not exist. Fix or remove:\n" + "\n".join(problems)
